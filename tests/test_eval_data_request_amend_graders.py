"""Fixture tests for the `claude plugin eval` suite of `data-request:amend` (issue #356).

Each case in evals/claude/data-request/ is one acceptance example from the issue.
Its answer is a classification, not a rewritten file, so the regex graders are
hand-written against the skill's fixed `classification:` and hand-off field lines
(scripts/generate_eval_graders.py only generates Go-file graders and leaves these
alone). Every case's fixtures.yaml replies are graded here in Python's `re` and in
Node's JavaScript engine, which is what `claude plugin eval` runs; the two must
agree. No model call is made.
"""

import json
import re
import shutil
import subprocess
import sys
import time
import unittest
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SUITE = REPO / "evals/claude/data-request"

# Acceptance example -> the grader that decides its outcome.
CASES = {
    "amend-rename-safe": "classified-safe",
    "amend-reorder-safe": "classified-safe",
    "amend-icd-code-engineer": "classified-engineer",
    "amend-derived-column-engineer": "classified-engineer",
    "amend-new-element-governance": "classified-engineer",
    "amend-generated-sql-refused": "refused",
}
EXTRA = {
    "amend-icd-code-engineer": {"hand-off"},
    "amend-derived-column-engineer": {"hand-off"},
    "amend-new-element-governance": {"hand-off", "governance-check"},
    "amend-generated-sql-refused": {"supported-route"},
}
MUTATING_TOOLS = {"Bash", "Write", "Edit", "NotebookEdit"}

NODE = shutil.which("node")
NODE_SCRIPT = """
const {patterns, reply} = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const out = {};
for (const [name, source] of Object.entries(patterns)) out[name] = new RegExp(source).test(reply);
process.stdout.write(JSON.stringify(out));
"""


def meta(path: Path) -> dict:
    return yaml.safe_load(path.read_text().split("\n---\n")[0].removeprefix("---\n"))


def graders(case: str) -> dict:
    return {p.stem: meta(p) for p in sorted((SUITE / case / "graders").glob("*.md"))}


def regex_sources(case: str) -> dict:
    return {name: g["pattern"] for name, g in graders(case).items() if g["type"] == "regex"}


class SuiteShape(unittest.TestCase):
    def test_suite_covers_every_acceptance_example(self):
        found = {p.parent.name for p in SUITE.glob("*/prompt.md")}
        self.assertEqual(found, set(CASES))

    def test_cases_answer_in_text_without_mutating_tools(self):
        for case in CASES:
            with self.subTest(case=case):
                front = meta(SUITE / case / "prompt.md")
                self.assertTrue(front["description"])
                self.assertIn("amend", front["tags"])
                self.assertIn("Skill", front["allowed_tools"])
                self.assertFalse(MUTATING_TOOLS & set(front["allowed_tools"]))

    def test_every_case_detects_the_amend_skill(self):
        for case in CASES:
            with self.subTest(case=case):
                fired = graders(case)["skill-fired"]
                self.assertEqual((fired["type"], fired["tool"]), ("tool_used", "Skill"))
                matcher = re.compile(fired["input_match"])
                self.assertTrue(matcher.search('{"skill": "data-request:amend"}'))
                self.assertTrue(matcher.search('{"skill":"amend"}'))
                self.assertFalse(matcher.search('{"skill": "data-request:fix"}'))

    def test_outcome_graders_are_present_and_hand_written(self):
        for case, outcome in CASES.items():
            with self.subTest(case=case):
                names = set(graders(case))
                self.assertIn(outcome, names)
                self.assertLessEqual(EXTRA.get(case, set()), names)
                for path in (SUITE / case / "graders").glob("*.md"):
                    # Not generator output, so generate_eval_graders.py leaves them alone.
                    self.assertNotIn("GENERATED by", path.read_text())
                    self.assertIn(meta(path)["type"], {"regex", "tool_used"})
                for name, source in regex_sources(case).items():
                    re.compile(source)
                    self.assertEqual(graders(case)[name]["target"], "last_message")

    def test_generator_check_ignores_the_hand_written_graders(self):
        result = subprocess.run(
            [sys.executable, str(REPO / "scripts/generate_eval_graders.py"), str(REPO), "--check"],
            capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


@unittest.skipUnless(NODE, "Node required for Python/JavaScript grader agreement")
class FixtureGrades(unittest.TestCase):
    def grade(self, sources: dict, reply: str) -> set:
        """Names of the graders that FAIL the reply (checked in both engines)."""
        python = {name: bool(re.search(src, reply)) for name, src in sources.items()}
        result = subprocess.run(
            [NODE, "-e", NODE_SCRIPT], input=json.dumps({"patterns": sources, "reply": reply}),
            capture_output=True, text=True, check=True, timeout=30,
        )
        self.assertEqual(json.loads(result.stdout), python, "JavaScript and Python disagree")
        return {name for name, ok in python.items() if not ok}

    def test_empty_reply_fails_every_regex_grader(self):
        for case in CASES:
            with self.subTest(case=case):
                sources = regex_sources(case)
                self.assertEqual(self.grade(sources, ""), set(sources))

    def test_case_fixtures(self):
        for case, outcome in CASES.items():
            fixtures = yaml.safe_load((SUITE / case / "fixtures.yaml").read_text())
            sources = regex_sources(case)
            self.assertTrue(fixtures["pass"], case)
            for fixture in fixtures["pass"]:
                with self.subTest(case=case, fixture=fixture["name"]):
                    self.assertEqual(self.grade(sources, fixture["reply"]), set())
            discriminating = False
            for fixture in fixtures["fail"]:
                with self.subTest(case=case, fixture=fixture["name"]):
                    fails = set(fixture["fails"])
                    self.assertTrue(fails, "a fail fixture must name the graders it fails")
                    self.assertEqual(self.grade(sources, fixture["reply"]), fails)
                    discriminating |= outcome in fails
            self.assertTrue(discriminating, f"{case}: no fixture fails the {outcome} grader")

    def test_large_replies_grade_quickly(self):
        reply = ("```sql\n" + "SELECT 1 AS x\n" * 2000 + "classification `\n" * 2000) * 3
        for case in CASES:
            with self.subTest(case=case):
                start = time.monotonic()
                self.grade(regex_sources(case), reply)
                self.assertLess(time.monotonic() - start, 5)


if __name__ == "__main__":
    unittest.main()
