"""Fixture tests for the triage field-gap eval cases (issues #378, #381 and #384).

The `field-*` cases in evals/claude/data-request/ come from field reports on the September
2026 triages: a renamed repository's link that still redirects, a `merged: false` listing
for a merged PR, a verbal decision against the newest written comment, a read of another
child's branch that must not check it out, and a legacy-template seed whose `answers.yaml`
does not parse. Their regex graders are hand-written against one fenced yaml block (the
generator leaves them alone). Every case's fixtures.yaml replies are graded here in
Python's `re` and, when `node` is on PATH, in JavaScript too; the two must agree. No model
call is made.
"""

import json
import re
import shutil
import subprocess
import sys
import time
import unittest
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SUITE = REPO / "evals" / "claude" / "data-request"

CASES = {
    "field-renamed-repo-redirect": {"redirect-resolved", "redirect-not-stale", "merged-from-merged-at",
                                    "verbal-unlinked"},
    "field-read-branch-no-checkout": {"reads-without-checkout", "legacy-template-seed", "answers-invalid",
                                      "pixi-skipped"},
}
MUTATING_TOOLS = {"Bash", "Write", "Edit", "NotebookEdit"}

NODE = shutil.which("node")
NODE_SCRIPT = """
const {patterns, reply} = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const out = {};
for (const [name, source] of Object.entries(patterns)) out[name] = new RegExp(source).test(reply);
process.stdout.write(JSON.stringify(out));
"""


def split_frontmatter(path: Path) -> tuple[dict, str]:
    parts = path.read_text().split("---\n", 2)
    return (yaml.safe_load(parts[1]) or {}), parts[2]


def graders(case: str) -> dict:
    return {p.stem: split_frontmatter(p)[0] for p in sorted((SUITE / case / "graders").glob("*.md"))}


def regex_sources(case: str) -> dict:
    return {name: g["pattern"] for name, g in graders(case).items() if g["type"] == "regex"}


class SuiteShape(unittest.TestCase):
    def test_every_field_case_is_covered(self):
        # test_eval_data_request_graders.py owns the other triage cases; amend-* has its own file.
        self.assertEqual({p.parent.name for p in SUITE.glob("field-*/prompt.md")}, set(CASES))
        for case, names in CASES.items():
            with self.subTest(case=case):
                self.assertEqual(set(regex_sources(case)), names)

    def test_prompts_answer_from_inline_evidence(self):
        for case in CASES:
            meta, prompt = split_frontmatter(SUITE / case / "prompt.md")
            with self.subTest(case=case):
                for key in ("description", "runs", "max_turns", "timeout_seconds", "allowed_tools"):
                    self.assertIn(key, meta)
                self.assertIn("triage", meta["tags"])
                self.assertGreaterEqual(meta["runs"], 3)
                self.assertIn("Skill", meta["allowed_tools"])
                self.assertFalse(MUTATING_TOOLS & set(meta["allowed_tools"]))
                self.assertRegex(prompt, r"(?i)triage only")
                self.assertNotRegex(prompt, r"(?:^|\s)(?:/home/|~/)", "cases run in a sandbox cwd")

    def test_triage_skill_fires(self):
        for case in CASES:
            with self.subTest(case=case):
                fired = graders(case)["skill-fired"]
                self.assertEqual((fired["type"], fired["tool"]), ("tool_used", "Skill"))
                matcher = re.compile(fired["input_match"])
                self.assertTrue(matcher.search('{"skill": "data-request:triage"}'))
                self.assertTrue(matcher.search('{"skill":"triage"}'))
                self.assertFalse(matcher.search('{"skill": "data-request:bootstrap"}'))

    def test_graders_are_hand_written_regexes_on_the_last_message(self):
        for case in CASES:
            for path in (SUITE / case / "graders").glob("*.md"):
                with self.subTest(case=case, grader=path.stem):
                    self.assertNotIn("GENERATED by", path.read_text())
            for name, source in regex_sources(case).items():
                re.compile(source)
                self.assertEqual(graders(case)[name]["target"], "last_message")

    def test_generator_check_ignores_the_hand_written_graders(self):
        result = subprocess.run(
            [sys.executable, str(REPO / "scripts" / "generate_eval_graders.py"), str(REPO), "--check"],
            capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


class FixtureGrades(unittest.TestCase):
    def grade(self, sources: dict, reply: str) -> set:
        """Names of the graders that FAIL the reply (checked in both engines when node exists)."""
        python = {name: bool(re.search(src, reply)) for name, src in sources.items()}
        if NODE:
            result = subprocess.run(
                [NODE, "-e", NODE_SCRIPT], input=json.dumps({"patterns": sources, "reply": reply}),
                capture_output=True, text=True, check=True, timeout=30,
            )
            self.assertEqual(json.loads(result.stdout), python, "JavaScript and Python disagree")
        return {name for name, ok in python.items() if not ok}

    def test_empty_reply_fails_every_regex_grader(self):
        for case in CASES:
            with self.subTest(case=case):
                sources = regex_sources(case)
                self.assertEqual(self.grade(sources, ""), set(sources))

    def test_case_fixtures(self):
        for case, names in CASES.items():
            fixtures = yaml.safe_load((SUITE / case / "fixtures.yaml").read_text())
            sources = regex_sources(case)
            self.assertTrue(fixtures["pass"], case)
            for fixture in fixtures["pass"]:
                with self.subTest(case=case, fixture=fixture["name"]):
                    self.assertEqual(self.grade(sources, fixture["reply"]), set())
            failed = set()
            for fixture in fixtures["fail"]:
                with self.subTest(case=case, fixture=fixture["name"]):
                    fails = set(fixture["fails"])
                    self.assertTrue(fails, "a fail fixture must name the graders it fails")
                    self.assertEqual(self.grade(sources, fixture["reply"]), fails)
                    failed |= fails
            self.assertEqual(failed, names, f"{case}: a grader has no failing fixture")

    def test_only_the_last_yaml_block_counts(self):
        for case in CASES:
            sources = regex_sources(case)
            good = yaml.safe_load((SUITE / case / "fixtures.yaml").read_text())["pass"][0]["reply"]
            with self.subTest(case=case):
                self.assertEqual(self.grade(sources, good + "\n```yaml\nnote: see above\n```\n"), set(sources))

    def test_long_replies_grade_quickly(self):
        filler = "Line with `git checkout`, THHSRDLENQ-9005 and a - dash.\n" * 400
        for case in CASES:
            sources = regex_sources(case)
            good = yaml.safe_load((SUITE / case / "fixtures.yaml").read_text())["pass"][0]["reply"]
            with self.subTest(case=case):
                start = time.monotonic()
                self.grade(sources, filler + good + filler)
                self.grade(sources, filler + "```yaml\n" + filler)
                self.assertLess(time.monotonic() - start, 5)


if __name__ == "__main__":
    unittest.main()
