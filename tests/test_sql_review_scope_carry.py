class BodyComparison(Base):
    """Only the leading comment header is ignored; everything after it is compared byte for byte."""

    def verdict(self, before, after, env=None):
        v1 = scope_items()
        self.sql.write_bytes(before.encode())
        self.publish(self.review(1, before, **v1))
        self.assertEqual(run(["snapshot", "q", "q.sql"], self.p.root).returncode, 0)
        self.sql.write_bytes(after.encode())
        a1 = v1["assumptions"][0]
        self.draft.write_text(json.dumps(self.review(2, after, assumptions=[candidate(a1)], limitations=[])))
        r = run(["carryforward", "q", "review", str(self.draft)], self.p.root, env=env)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        return json.loads(r.stdout)

    def fresh_project(self):
        self.setUp()

    def test_header_only_changes_are_unchanged(self):
        for name, before, after in SAME:
            with self.subTest(name):
                self.fresh_project()
                out = self.verdict(before, after)
                self.assertTrue(out["sql_body_unchanged"])
                self.assertEqual(self.basis(out["carry"]), {"A1": "sql-body-unchanged"})

    def test_real_changes_and_odd_headers_are_changes(self):
        for name, before, after in CHANGED:
            with self.subTest(name):
                self.fresh_project()
                out = self.verdict(before, after)
                self.assertFalse(out["sql_body_unchanged"])
                self.assertEqual(out["carry"], [])
                self.assertEqual([b["id"] for b in out["bulk"]], ["A1"])

    def test_hidden_code_edits_cannot_be_published_as_carried(self):
        cases = {name: (before, after) for name, before, after in CHANGED}
        for name in ("nested header, literal edit", "lone CR in a leading -- line", "lone CR after a block and --"):
            with self.subTest(name):
                self.fresh_project()
                before, after = cases[name]
                out = self.verdict(before, after)
                self.assertEqual(out["carry"], [])
                a1 = scope_items()["assumptions"][0]
                forged = carried(a1, 2, carried_basis="sql-body-unchanged")
                r = self.publish(self.review(2, after, assumptions=[forged], limitations=[]), expected=4)
                self.assertIn("A1", r.stdout + r.stderr)

    def test_a_failing_normaliser_counts_as_a_change(self):
        # awk failing (and printing nothing) for both files must not compare two empty digests.
        stub = Path(self.tmp.name) / "stub-bin"
        stub.mkdir()
        (stub / "awk").write_text("#!/bin/sh\nexit 1\n")
        (stub / "awk").chmod(stat.S_IRWXU)
        env = {"PATH": f"{stub}{os.pathsep}{os.environ['PATH']}"}
        out = self.verdict(SQL_V1, CODE_EDIT, env=env)
        self.assertFalse(out["sql_body_unchanged"])
        self.assertEqual(out["carry"], [])


class ReviewBulk(Base):
    """A review item whose SQL changed under it: one bulk question with its location, never silent."""

    def setUp(self):
        super().setUp()
        self.v1 = scope_items()
        self.publish(self.review(1, SQL_V1, **self.v1))
        self.assertEqual(run(["snapshot", "q", "q.sql"], self.p.root).returncode, 0)
        self.sql.write_text(CODE_EDIT)

