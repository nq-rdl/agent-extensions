#!/usr/bin/env python3
"""Generate regex graders for `claude plugin eval` cases from a readable spec.

A case that asks for a rewritten Go file is graded on that file only, never on the
surrounding prose: replies routinely quote the original identifiers while
explaining a rename, so a check over the whole reply fails correct answers. Doing
that in one JavaScript regex (the only deterministic grader the CLI offers) needs
a long shared prefix, so the patterns are generated rather than hand-written.

Every `evals/claude/<plugin>/<case>/graders.spec.yaml` lists the file's package
and, per grader, the text that must (`need`) and must not (`forbid`) appear in
code. The generated pattern:

- anchors on the LAST fenced go block (3+ backticks or tildes, indented up to 3
  spaces) that opens with the package clause — the rewrite, not a quoted "before";
- ends at the matching closing fence at a line start (a backreference);
- consumes Go comments and literals atomically, `(?=(...))\\N`, so names quoted in
  them are neither required nor forbidden, backticks inside them cannot end the
  block, and matching stays linear (a non-atomic token backtracks exponentially);
- therefore fails on an empty or code-less reply — no vacuous passes.

Known limits, accepted: malformed literals and a file split across several blocks.
Fixtures in each spec are graded by tests/test_eval_regex_graders.py in both Python
and Node, which must agree.

CLI:
    pixi run python3 scripts/generate_eval_graders.py [REPO_ROOT]          # write
    pixi run python3 scripts/generate_eval_graders.py [REPO_ROOT] --check  # fail on drift
"""
from __future__ import annotations

import itertools
import re
import sys
from pathlib import Path

import yaml

SPEC_NAME = "graders.spec.yaml"
SKIP = r"""//[^\n]*|/\*[\s\S]*?\*/|"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)+'|`[^`]*`"""
START = r"""//|/\*|"|'|`"""


def build_pattern(package: str, needs: list[str], forbid: str | None) -> str:
    # Embedded captures would shift the generated atomic-token backreferences.
    for pattern in [*needs, *([forbid] if forbid else [])]:
        if re.compile(pattern).groups:
            raise ValueError(f"Capturing groups are not supported; use (?:...) instead: {pattern!r}")
    pkg = (r"[ \t]*go[^\n]*\n\s*(?:(?://[^\n]*\n|/\*[^*]*(?:\*(?!/)[^*]*)*\*/)\s*)*"
           + r"package\s+" + re.escape(package) + r"\b")
    group = itertools.count(1)
    opening = r" {0,3}(?:`{3,}|~{3,})"

    def fences() -> tuple[str, str]:
        fence, marker = next(group), next(group)
        # Capture the marker separately so extra closing markers cannot mix
        # backticks and tildes. Do not backtrack to a shorter opening run.
        return (r"((`|~)\%d{2,})(?![`~])" % marker,
                r"\%d\%d*[ \t\r]*(?:\n|$)" % (fence, marker))

    def markdown(exclude_package: bool = False) -> str:
        # Consume whole fenced blocks atomically from a line boundary. Never
        # restart at a shorter fence inside a block comment or another example.
        token = next(group)
        opener, closer = fences()
        excluded = (r"(?!" + opening + pkg + ")") if exclude_package else ""
        fenced = (excluded + r" {0,3}" + opener + r"[^\n]*\n(?:[^\n]*\n)*?"
                  + r" {0,3}" + closer)
        return (r"(?:(?=(" + fenced + r"))\%d" % token
                + r"|(?!" + opening + r")[^\n]*(?:\n|(?![\s\S])))*")

    prefix = markdown()
    opener, closer = fences()
    close = r"\n {0,3}" + closer

    def code(guard: str) -> str:
        # Zero or more steps through code: a whole comment/literal, or one character
        # that neither starts one nor begins forbidden text.
        return (r"(?:(?!" + close + r")(?:(?=(" + SKIP + r"))\%d" % next(group)
                + r"|(?!" + guard + r")[\s\S]))*")

    out = "^" + prefix + r" {0,3}" + opener + pkg
    for need in needs:
        out += r"(?=" + code(START) + need + ")"
    out += code(START + (("|" + forbid) if forbid else "")) + close
    # The suffix can contain prose and unrelated blocks, but no later top-level
    # file for this package. A failing final rewrite cannot fall back to an
    # earlier passing one.
    return out + markdown(exclude_package=True) + r"(?![\s\S])"


def render(spec: dict, grader: dict) -> str:
    pattern = build_pattern(spec["package"], grader.get("need", []), grader.get("forbid"))
    return (
        "---\n"
        "type: regex\n"
        f"# GENERATED by scripts/generate_eval_graders.py from ../{SPEC_NAME} — do not hand-edit.\n"
        f"# {grader['why']}\n"
        "pattern: '" + pattern.replace("'", "''") + "'\n"
        "target: last_message\n"
        "---\n"
    )


def specs(repo: Path) -> list[Path]:
    return sorted((repo / "evals" / "claude").glob(f"*/*/{SPEC_NAME}"))


def expected_files(spec_path: Path) -> dict[Path, str]:
    spec = yaml.safe_load(spec_path.read_text())
    graders_dir = spec_path.parent / "graders"
    return {graders_dir / f"{g['name']}.md": render(spec, g) for g in spec["graders"]}


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    do_check = "--check" in argv
    positional = [a for a in argv if not a.startswith("--")]
    repo = Path(positional[0] if positional else ".").resolve()

    expected = {}
    for spec_path in specs(repo):
        expected.update(expected_files(spec_path))
    # Scan independently of specs so deleted or renamed cases cannot leave stale
    # graders behind. Hand-written graders of other types are left alone.
    generated = {
        p for p in (repo / "evals" / "claude").glob("*/*/graders/*.md")
        if "GENERATED by scripts/generate_eval_graders.py" in p.read_text()
    }
    drift = []
    for stale in sorted(generated - set(expected)):
        if do_check:
            drift.append(f"{stale.relative_to(repo)}: not in any spec")
        else:
            stale.unlink()
    for path, text in expected.items():
        if path.exists() and path.read_text() == text:
            continue
        if do_check:
            drift.append(f"{path.relative_to(repo)}: out of date")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

    if drift:
        for line in drift:
            print(f"::error::{line} — run `pixi run python3 scripts/generate_eval_graders.py .`", file=sys.stderr)
        return 1
    print("Eval regex graders are in sync." if do_check else "Eval regex graders written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
